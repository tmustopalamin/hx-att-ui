const primeReactConfig = { appendTo: "self" as AppendToType };

export default function PrimeReactLocaleProvider({
  children,
}: Readonly<{ children: ReactNode }>) {
  const { locale } = useI18n();

  useEffect(() => {
    setPrimeReactLocale(locale);
  }, [locale]);

  const value = useMemo(() => ({ ...primeReactConfig, locale }), [locale]);
  return <PrimeReactProvider value={value}>{children}</PrimeReactProvider>;
}
